export const districtSlug = metroSlug;

export const DISTRICT_LIST = Array.from(new Set(ADDRESSES.map((a) => a.district))).sort((a, b) => a.localeCompare(b, "ru"));

export type District = {
  name: string;
  about: string;
  addresses: Address[];
  okrug: string;
  ifns: string[];
  metros: string[];
  minPrice: number;
};

export const getDistrictBySlug = (slug: string): District | undefined => {
  const name = DISTRICT_LIST.find((d) => districtSlug(d) === slug);
  if (!name) return undefined;
  const addresses = ADDRESSES.filter((a) => a.district === name);
  const u = (k: keyof Address) => Array.from(new Set(addresses.map((a) => String(a[k]))));
  return {
    name,
    about: ABOUT[name] ?? `Район ${name} — удобное расположение для регистрации компании в Москве.`,
    addresses,
    okrug: addresses[0].okrug,
    ifns: u("ifns").sort((a, b) => Number(a) - Number(b)),
    metros: u("metro"),
    minPrice: Math.min(...addresses.map((a) => a.price)),
  };
};

